#!/usr/bin/env tsx
/**
 * The SSH runtime install transaction has ONE editable source:
 * packages/cli/src/remote-host-scripts.ts, which `claudexor remote install`
 * runs. This renders the macOS app's copy, RemoteRuntimeScripts.swift, from
 * it; `--check` fails when the committed Swift file differs (run by
 * `pnpm fixtures:swift:check`, a release gate).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { INSTALL_SCRIPT, ROLLBACK_SCRIPT } from "../packages/cli/src/remote-host-scripts.js";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const swiftPath = join(
  repoRoot,
  "apps/macos/ClaudexorApp/Sources/ClaudexorApp/RemoteRuntimeScripts.swift",
);
const INDENT = "        ";

/** A Swift multi-line literal whose value is exactly `value`: every backslash
 * is escaped (no `\(` interpolation, no line continuation can arise) and each
 * line carries the closing delimiter's indentation, which Swift strips. */
function swiftMultiline(name: string, value: string): string {
  if (value.includes('"""') || value.includes("\r")) {
    throw new Error(`${name} contains text a Swift multi-line literal cannot carry verbatim`);
  }
  const lines = value.split("\n");
  if (lines.some((line) => line !== line.trimEnd())) {
    throw new Error(`${name} has trailing whitespace, which would not survive review tools`);
  }
  const body = lines
    .map((line) => (line === "" ? "" : `${INDENT}${line.replaceAll("\\", "\\\\")}`))
    .join("\n");
  return `    static let ${name} = """\n${body}\n${INDENT}"""`;
}

const rendered = [
  "// GENERATED by scripts/gen-remote-runtime-scripts.ts from",
  "// packages/cli/src/remote-host-scripts.ts, the one editable source of the SSH",
  "// runtime install transaction (`claudexor remote install` runs the same text).",
  "// Do not edit here: change the TypeScript source and run `pnpm fixtures:swift`.",
  "extension RemoteRuntimeInstaller {",
  swiftMultiline("installScript", INSTALL_SCRIPT),
  "",
  swiftMultiline("rollbackScript", ROLLBACK_SCRIPT),
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(swiftPath, "utf8") !== rendered) {
    console.error(
      "RemoteRuntimeScripts.swift is stale or hand-edited; regenerate: pnpm fixtures:swift",
    );
    process.exit(1);
  }
} else {
  writeFileSync(swiftPath, rendered);
}
