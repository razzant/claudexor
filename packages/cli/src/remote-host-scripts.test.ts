import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import * as os from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  INSTALL_SCRIPT,
  INSTALL_SCRIPT_ESCAPED,
  PREFLIGHT_SCRIPT,
  RECIPIENT_MISMATCH,
  ROLLBACK_SCRIPT,
  installCommand,
  installPointer,
  posixQuote,
} from "./remote-host-scripts.js";

const RECIPIENT = {
  uid: 1000,
  user: "builder",
  home: "/home/builder",
  hostname: "synthetic-host",
  os: "Linux",
  machine: "x86_64",
};
const QUOTED = `'1000' 'builder' '/home/builder' 'synthetic-host' 'Linux' 'x86_64'`;

const SWIFT = resolve(
  import.meta.dirname,
  "../../../apps/macos/ClaudexorApp/Sources/ClaudexorApp/RemoteRuntimeScripts.swift",
);

/** The value of `static let <name> = """ … """` as Swift evaluates it: strip the
 * closing delimiter's indentation, then apply the escapes these literals may
 * contain. Independent of the generator, so a rendering bug cannot hide. */
function swiftLiteral(source: string, name: string): string {
  const open = `static let ${name} = """\n`;
  const start = source.indexOf(open);
  expect(start).toBeGreaterThanOrEqual(0);
  const rest = source.slice(start + open.length);
  const close = /\n([ \t]*)"""/.exec(rest);
  expect(close).not.toBeNull();
  const indent = close![1]!;
  const text = rest
    .slice(0, close!.index)
    .split("\n")
    .map((line) => (line.trim() === "" ? "" : line.slice(indent.length)))
    .join("\n");
  return text.replace(/\\([\\nt"'\n])/g, (_, escaped: string) =>
    escaped === "\n" ? "" : ({ "\\": "\\", n: "\n", t: "\t", '"': '"', "'": "'" }[escaped] ?? ""),
  );
}

describe("the one install transaction shared with the macOS app", () => {
  it("the generated Swift literals evaluate to exactly the CLI's scripts", () => {
    const source = readFileSync(SWIFT, "utf8");
    expect(source.startsWith("// GENERATED by scripts/gen-remote-runtime-scripts.ts")).toBe(true);
    expect(swiftLiteral(source, "installScript")).toBe(INSTALL_SCRIPT);
    expect(swiftLiteral(source, "rollbackScript")).toBe(ROLLBACK_SCRIPT);
  });

  it("never asks for elevated rights and keeps every path under the user's home", () => {
    for (const script of [INSTALL_SCRIPT, ROLLBACK_SCRIPT]) {
      expect(script).not.toMatch(/\bsudo\b|\bsu\b|\bdoas\b/);
      expect(script).toContain('root="$HOME/.claudexor/remote"');
    }
  });

  it("quotes every remote argument for a POSIX login shell", () => {
    expect(posixQuote("it's")).toBe(`'it'"'"'s'`);
  });

  it("gives a controller-side install one writing step, with its own directory and pointer", () => {
    const sha = "a".repeat(64);
    const flow = "b".repeat(32);
    const install = installCommand(RECIPIENT, "9.0.1", sha, flow);
    const installArgs = `${QUOTED} '9.0.1' '${sha}' '-' '-' '-' '${flow}'`;
    expect(install.startsWith("sh -c '")).toBe(true);
    expect(install.endsWith(` claudexor-install ${installArgs}`)).toBe(true);
    // One line for the login shell, whatever shell that is.
    expect(install).not.toContain("\n");
    expect(installPointer("9.0.1", sha, flow)).toBe(`versions/9.0.1-${sha}-${flow}`);
  });

  it("carries the whole transaction in the step's one-line command, so its input is only the archive", () => {
    // printf %b's octal escapes, decoded here independently of the encoder.
    const decoded = INSTALL_SCRIPT_ESCAPED.replace(/\\0([0-7]{3})/g, (_, octal: string) =>
      String.fromCharCode(Number.parseInt(octal, 8)),
    );
    expect(decoded).toBe(INSTALL_SCRIPT);
    // Nothing a login shell acts on inside quotes, nor a line break, is left.
    expect(INSTALL_SCRIPT_ESCAPED).not.toMatch(/[\n!']|\\(?!0[0-7]{3})/);
    expect(installCommand(RECIPIENT, "9.0.1", "a".repeat(64), "b".repeat(32))).toContain(
      INSTALL_SCRIPT_ESCAPED,
    );
  });

  it("reads an installed runtime's two small files and runs nothing from its directory", () => {
    expect(PREFLIGHT_SCRIPT).toContain('"$dir/runtime.json"');
    expect(PREFLIGHT_SCRIPT).toContain('"$dir/.archive-sha256"');
    expect(PREFLIGHT_SCRIPT).not.toContain("bin/claudexor");
    expect(PREFLIGHT_SCRIPT).not.toContain("remote probe");
    // No path in that directory stands where the shell runs a command.
    expect(PREFLIGHT_SCRIPT).not.toMatch(
      /(?:^|[;&|({]|\$\(|\bthen|\bdo|\belse)\s*"?\$(?:dir|file|root\/\$target)/m,
    );
  });

  it.skipIf(process.platform === "win32")(
    "refuses before writing anything when the server's name is not the confirmed one",
    () => {
      // The shared fixture's name, which this machine does not have; every other
      // confirmed fact is this account's own, with an empty HOME.
      expect(os.hostname()).not.toBe(RECIPIENT.hostname);
      const home = mkdtempSync(join(os.tmpdir(), "claudexor-recipient-"));
      try {
        const { uid, username } = os.userInfo();
        const recipient = {
          ...RECIPIENT,
          uid,
          user: username,
          home,
          os: os.type(),
          machine: os.machine(),
        };
        const command = installCommand(recipient, "9.0.1", "a".repeat(64), "b".repeat(32));
        const step = spawnSync("/bin/sh", ["-c", command], {
          env: { PATH: process.env["PATH"] ?? "/usr/bin:/bin", HOME: home },
          input: "",
          encoding: "utf8",
        });
        expect(step.status).toBe(77);
        expect(step.stdout).toBe(`${RECIPIENT_MISMATCH}\n`);
        expect(readdirSync(home)).toEqual([]);
      } finally {
        rmSync(home, { recursive: true, force: true });
      }
    },
  );
});
