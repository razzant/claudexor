import {
  closeSync,
  existsSync,
  lstatSync,
  openSync,
  readFileSync,
  writeFileSync,
  writeSync,
} from "node:fs";
import { join } from "node:path";

/**
 * D-14 layer 3 (AGENTS.md compatibility) — an envelope-local `CLAUDE.md` bridge.
 *
 * Codex, Cursor, and OpenCode read a project's `AGENTS.md` natively; Claude Code
 * reads `CLAUDE.md`. When a project standardizes on ONE `AGENTS.md`, Claudexor
 * may need a compatibility bridge in a disposable Git envelope. The bridge is
 * never written into the user's live project root. Its body is the official
 * Anthropic import form (`@AGENTS.md`) plus a Claudexor ownership marker.
 * File creation is not evidence that a model read the instructions.
 *
 * Fences (mirroring the automatic git-init boundary):
 *   - it acts ONLY when the target directory has `AGENTS.md` and no `CLAUDE.md`;
 *   - the create is EXCLUSIVE (`O_CREAT|O_EXCL`, the Node `wx` flag): a
 *     hand-written `CLAUDE.md` — or one a racing prep just wrote — is NEVER
 *     overwritten;
 *   - it is NO-FOLLOW: anything already occupying the path (a regular file, a
 *     symlink — even a dangling one — or a directory) is refused, so the bridge
 *     can never clobber or write through a link;
 *   - it is IDEMPOTENT: a second (or concurrent) prep finds the file and does
 *     nothing, so at most one file ever results.
 */

/** The exact bytes written into a generated `CLAUDE.md`. */
export const CLAUDE_BRIDGE_MARKER =
  "claudexor:generated envelope claude-bridge v1 — disposable compatibility file; reading not confirmed";
export const CLAUDE_BRIDGE_CONTENT = `@AGENTS.md\n\n<!-- ${CLAUDE_BRIDGE_MARKER} -->\n`;

/** Exact bytes emitted before the CX590 marker was scoped to envelopes. */
export const LEGACY_CLAUDE_BRIDGE_CONTENT =
  "@AGENTS.md\n\n<!-- claudexor:generated claude-bridge v1 — safe to edit; delete to stop bridging -->\n";

/** Which generated bytes a writer emitted: the current writer, or one from before CX590. */
export type ClaudeBridgeGeneration = "envelope-v1" | "legacy-v1";
/** The generation `ensureClaudeBridge` writes now. */
export const CURRENT_CLAUDE_BRIDGE_GENERATION: ClaudeBridgeGeneration = "envelope-v1";

export type ClaudeBridgeReason =
  /** No `AGENTS.md` at the project root — nothing to bridge to. */
  | "no_agents"
  /** A `CLAUDE.md` (file, symlink, or directory) already exists — never touched. */
  | "claude_exists"
  /** Lost an exclusive-create race to a concurrent prep — the other prep created it. */
  | "race_lost"
  /** This call created the bridge file. */
  | "created";

export interface ClaudeBridgeResult {
  /** True only when THIS call created the file. */
  created: boolean;
  /** Absolute path of the (would-be) `CLAUDE.md`. */
  path: string;
  reason: ClaudeBridgeReason;
}

/**
 * Create the thin `CLAUDE.md` bridge at `projectRoot` when — and only when — the
 * root has `AGENTS.md` and no `CLAUDE.md`. Returns what happened; `created` is
 * true for exactly one caller across any number of concurrent invocations.
 * The caller restricts this to a disposable envelope or another explicitly
 * owned compatibility directory; it must never target a user's live project
 * root.
 */
export function ensureClaudeBridge(projectRoot: string): ClaudeBridgeResult {
  const agentsPath = join(projectRoot, "AGENTS.md");
  const claudePath = join(projectRoot, "CLAUDE.md");

  // Only bridge when AGENTS.md is present as the source of truth.
  if (!existsSync(agentsPath)) return { created: false, path: claudePath, reason: "no_agents" };

  // No-follow refusal: lstat does NOT dereference the final component, so a
  // symlink named CLAUDE.md (valid OR dangling), a regular file, or a directory
  // all surface here and are left untouched. ENOENT means the path is free.
  try {
    lstatSync(claudePath);
    return { created: false, path: claudePath, reason: "claude_exists" };
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
  }

  // Exclusive create is the atomic race fence: `wx` opens with O_CREAT|O_EXCL, so
  // if any path (including a symlink) appears between the lstat above and this
  // open, the open fails EEXIST and we DO NOT overwrite. Exactly one concurrent
  // prep wins; the losers report `race_lost`.
  let fd: number;
  try {
    fd = openSync(claudePath, "wx", 0o644);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "EEXIST")
      return { created: false, path: claudePath, reason: "race_lost" };
    throw err;
  }
  try {
    writeSync(fd, CLAUDE_BRIDGE_CONTENT);
  } finally {
    closeSync(fd);
  }
  return { created: true, path: claudePath, reason: "created" };
}

/** The `CLAUDE.md` basename a diff-capture exclude targets. */
export const CLAUDE_BRIDGE_BASENAME = "CLAUDE.md";

/** Each generation's bridge as raw bytes, for exact-content comparison. */
const CLAUDE_BRIDGE_BYTES: Readonly<Record<ClaudeBridgeGeneration, Buffer>> = {
  "envelope-v1": Buffer.from(CLAUDE_BRIDGE_CONTENT, "utf8"),
  "legacy-v1": Buffer.from(LEGACY_CLAUDE_BRIDGE_CONTENT, "utf8"),
};

/**
 * True when `<worktreeRoot>/CLAUDE.md` is an UNMODIFIED Claudexor-generated
 * bridge of `generation` — i.e. its bytes are exactly the content that
 * generation's writer emitted. Diff capture uses this to exclude exactly the
 * pristine generated bridge (and only it) from an envelope candidate's patch, so the bridge written into a disposable envelope
 * tree never pollutes `patch.diff`.
 *
 * A-3: the decision is BYTE-EQUALITY, not marker substring. A substring check
 * silently dropped a candidate that EDITED `CLAUDE.md` while keeping the marker
 * comment (real work lost from `patch.diff`). Any candidate edit — even one that
 * retains the marker, or only appends to the bridge — now differs from the exact
 * bytes and is captured in the diff like any other real change. Only the pristine
 * generated file (which the candidate never touched) is excluded. A hand-written
 * or committed `CLAUDE.md` can match only by having exactly these bytes, which
 * is why the caller also requires the created-this-run fact below. A symlink at
 * the path is refused (no-follow), matching the writer's fence.
 *
 * The check is generation-specific: an envelope prepared before CX590 compares
 * against the legacy bytes its writer emitted, a current one against the
 * current bytes. A candidate that rewrites one generation's bridge into the
 * other's exact bytes made a real edit and is captured.
 *
 * A-3 residual: byte-equality is NECESSARY but NOT SUFFICIENT for exclusion. It
 * cannot distinguish our freshly written bridge from a candidate that rewrote a
 * PRE-EXISTING committed `CLAUDE.md` to exactly these bytes, so the caller
 * (`WorkspaceManager.diff`) AND-gates this check with the created-this-run fact:
 * exclude only when Claudexor created the bridge this run AND the bytes still
 * match. This function reports the byte condition alone.
 */
export function isGeneratedClaudeBridge(
  worktreeRoot: string,
  generation: ClaudeBridgeGeneration = CURRENT_CLAUDE_BRIDGE_GENERATION,
): boolean {
  const claudePath = join(worktreeRoot, CLAUDE_BRIDGE_BASENAME);
  try {
    if (lstatSync(claudePath).isSymbolicLink()) return false;
    return readFileSync(claudePath).equals(CLAUDE_BRIDGE_BYTES[generation]);
  } catch {
    return false;
  }
}

/**
 * Persistence of the created-this-run bridge fact (envelope-id-bound): the
 * WorkspaceManager's in-memory set dies with its instance, and a daemon
 * restart mid-run must not turn our own pristine bridge into a captured
 * candidate edit. The marker also names the generation whose bytes were
 * written. A missing/foreign/unknown marker stays fail-toward-CAPTURE.
 */
export function writeBridgeCreatedMarker(envelopeBase: string, envelopeId: string): void {
  try {
    writeFileSync(
      join(envelopeBase, "bridge-created.json"),
      JSON.stringify({
        envelope_id: envelopeId,
        created_at: new Date().toISOString(),
        generation: CURRENT_CLAUDE_BRIDGE_GENERATION,
      }) + "\n",
    );
  } catch {
    /* marker is an optimization over the in-memory set; never fail create */
  }
}

/**
 * The generation this envelope's persisted marker proves Claudexor wrote, or
 * null. A marker without `generation` predates CX590, whose writer could emit
 * only the legacy bytes; any other value is not ours to interpret.
 */
export function bridgeCreatedMarkerGeneration(
  envelopeBase: string,
  envelopeId: string,
): ClaudeBridgeGeneration | null {
  try {
    const marker = JSON.parse(readFileSync(join(envelopeBase, "bridge-created.json"), "utf8")) as {
      envelope_id?: unknown;
      generation?: unknown;
    };
    if (marker.envelope_id !== envelopeId) return null;
    if (marker.generation === undefined) return "legacy-v1";
    return marker.generation === CURRENT_CLAUDE_BRIDGE_GENERATION
      ? CURRENT_CLAUDE_BRIDGE_GENERATION
      : null;
  } catch {
    return null;
  }
}
