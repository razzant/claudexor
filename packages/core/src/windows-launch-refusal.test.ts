// Recorded bytes generated by the real npm cmd-shim package.
const fixtures = fileURLToPath(new URL("./fixtures/npm-launch/", import.meta.url));

/** The npm placeholder's class: shell text where the loader expects `MZ`. */
const PLACEHOLDER = 'echo "Error: native binary not installed." >&2\r\nexit 1\r\n';
const NODE_SCRIPT = "#!/usr/bin/env node\nconsole.log('ok')\n";

/** The PE minimum shape: `MZ`, e_lfanew at 0x3c, `PE\0\0`, then the machine. */
function image(machine = 0x8664): Buffer {
  const bytes = Buffer.alloc(512);
  bytes.write("MZ", 0, "latin1");
  bytes.writeUInt32LE(0x80, 0x3c);
  bytes.write("PE\0\0", 0x80, "latin1");
  bytes.writeUInt16LE(machine, 0x84);
  return bytes;
}

function dosHeader(signatureAt: number, size: number, signature = ""): Buffer {
  const bytes = Buffer.alloc(size);
  bytes.write("MZ", 0, "latin1");
  bytes.writeUInt32LE(signatureAt, 0x3c);
  if (signature) bytes.write(signature, signatureAt, "latin1");
  return bytes;
}

const NOT_IMAGES: Array<[string, Buffer]> = [
  ["an npm placeholder script", Buffer.from(PLACEHOLDER)],
  ["a zero-filled file", Buffer.alloc(4096)],
  ["a DOS header without PE", dosHeader(0x40, 0x80, "NE")],
  ["a header pointing past the end", dosHeader(0x1000, 0x40)],
];

let root: string;
beforeEach(() => {
  root = realpathSync(mkdtempSync(join(tmpdir(), "windows launch refusal ")));
  observer.attempts.length = 0;
  observer.allow.clear();
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

function file(path: string, bytes: Buffer | string): string {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
  return path;
}

/** A standard npm global install: the real cmd-shim launcher plus its declared bin. */
function npmInstall(prefix: string, entry: Buffer | string, kind: "native" | "node" = "native") {
  const name = kind === "native" ? "tool.exe" : "tool.cjs";
  const packageRoot = join(prefix, "node_modules", "@fixture", "tool");
  const target = file(join(packageRoot, "bin", name), entry);
  file(
    join(packageRoot, "package.json"),
    JSON.stringify({ name: "@fixture/tool", bin: { tool: `bin/${name}` } }),
  );
  const launcher = readFileSync(join(fixtures, `${kind}.cmd`), "utf8").replace(/\r?\n/g, "\r\n");
  return { shim: file(join(prefix, "tool.cmd"), launcher), target };
}

/** The spawn layer reads `process.platform`; report win32 for the duration of `run`. */
async function onWindows<T>(run: () => Promise<T>): Promise<T> {
  const original = Object.getOwnPropertyDescriptor(process, "platform")!;
  Object.defineProperty(process, "platform", { ...original, value: "win32" });
  try {
    return await run();
  } finally {
    Object.defineProperty(process, "platform", original);
  }
}

function thrown(run: () => unknown): unknown {
  try {
    run();
    return undefined;
  } catch (error) {
    return error;
  }
}

function escaped(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

describe("a provable non-image is never launched", () => {
  it("uses the trailing dot exactly as Windows spawn does", async () => {
    const bad = file(join(root, "tool.exe"), PLACEHOLDER);
    const bin = join(root, "tool.");
    expect(thrown(() => prepareHarnessCommand(bin, [], { PATH: root }, "win32"))).toMatchObject({
      code: "EFTYPE",
      path: bad,
    });
    await onWindows(async () => {
      await expect(runCapture(bin, [], { env: { PATH: root } })).rejects.toMatchObject({
        code: "EFTYPE",
        path: bad,
      });
      await expect(runCaptureRaw(bin, [], { env: { PATH: root } })).rejects.toMatchObject({
        code: "EFTYPE",
        path: bad,
      });
    });
    expect(observer.attempts).toEqual([]);
    writeFileSync(bad, image());
    expect(thrown(() => prepareHarnessCommand(bin, [], { PATH: root }, "win32"))).toBeUndefined();
  });

  it("names unlaunchable candidates in quoted PATH diagnostic fallbacks", async () => {
    const prefix = join(root, `tools${delimiter}local`);
    const candidate = join(prefix, "unavailable.exe");
    mkdirSync(candidate, { recursive: true });
    const shim = file(join(prefix, "unsupported.cmd"), "echo custom launcher\n");
    await onWindows(async () => {
      const env = { ...process.env, PATH: `"${prefix}"` };
      expect(brokenInstallAdvisory("unavailable", env, [])).toContain(candidate);
      expect(brokenInstallAdvisory("unsupported", env, [])).toContain(shim);
    });
    expect(observer.attempts).toEqual([]);
  });
  it.each(NOT_IMAGES)("rejects an npm launcher target that is %s, naming it", (_kind, bytes) => {
    const prefix = join(root, "npm");
    const { shim, target } = npmInstall(prefix, bytes);
    const resolution = resolveHarnessCommandOnPath("tool", prefix, "win32");
    expect(resolution.command).toBeNull();
    expect(resolution.skipped).toEqual([
      {
        path: shim,
        image: target,
        reason: expect.stringContaining(
          `launches ${target}, which is not a Windows executable image`,
        ),
      },
    ]);
    expect(resolution.refusal).toMatchObject({ code: "EFTYPE", path: target });
    // The refused file and the verdict lead, so a bounded diagnostic keeps them.
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: prefix }, "win32", root)),
    ).toMatchObject({
      code: "EFTYPE",
      path: target,
      message: expect.stringMatching(
        new RegExp(
          `^${escaped(`Cannot launch ${target}: it is not a Windows executable image (run by ${shim})`)}`,
        ),
      ),
    });
  });

  it("refuses in spawnProcess and runCaptureRaw before any spawn", async () => {
    const prefix = join(root, "npm");
    const { target } = npmInstall(prefix, PLACEHOLDER);
    const work = join(root, "work");
    mkdirSync(work);
    const options = { env: { PATH: prefix }, cwd: work };
    await expect(onWindows(() => runCapture("tool", ["--version"], options))).rejects.toMatchObject(
      {
        code: "EFTYPE",
        path: target,
      },
    );
    await expect(
      onWindows(() => runCaptureRaw("tool", ["--version"], options)),
    ).rejects.toMatchObject({ code: "EFTYPE", path: target });
    expect(observer.attempts).toEqual([]);
  });

  it.each([
    ["x64", 0x8664],
    ["x86", 0x014c],
    ["arm64", 0xaa64],
  ])(
    "keeps a %s PE launchable: the signature is shape, not an architecture verdict",
    async (_arch, machine) => {
      const prefix = join(root, "npm");
      const { shim, target } = npmInstall(prefix, image(machine));
      const resolution = resolveHarnessCommandOnPath("tool", prefix, "win32");
      expect(resolution.command).toEqual({ entrypoint: target, launcher: shim });
      expect(resolution.refusal ?? null).toBeNull();
      await expect(
        onWindows(() => runCapture("tool", [], { env: { PATH: prefix }, cwd: root })),
      ).rejects.toMatchObject({ code: "EOBSERVED" });
      expect(observer.attempts).toEqual([target]);
    },
  );

  it("takes a healthy later install, then recovers when the broken file is replaced", () => {
    const local = file(join(root, "local", "tool.exe"), PLACEHOLDER);
    const prefix = join(root, "npm");
    const { target } = npmInstall(prefix, image());
    const path = [dirname(local), prefix].join(delimiter);
    const resolution = resolveHarnessCommandOnPath("tool", path, "win32");
    expect(resolution.command?.entrypoint).toBe(target);
    expect(resolution.advisory).toContain(`${local} (is not a Windows executable image`);
    // Both broken: the bare name would reach the earlier placeholder.
    writeFileSync(target, PLACEHOLDER);
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: path }, "win32", root)),
    ).toMatchObject({
      code: "EFTYPE",
      path: local,
    });
    // Replacement needs no restart or invalidation: nothing remembers a refusal.
    writeFileSync(local, image());
    expect(prepareHarnessCommand("tool", [], { PATH: path }, "win32", root).binary).toBe(local);
  });

  it("treats `.com` images exactly like `.exe`", () => {
    const dir = join(root, "bin");
    const com = file(join(dir, "tool.com"), PLACEHOLDER);
    expect(resolveHarnessCommandOnPath("tool", dir, "win32")).toMatchObject({
      command: null,
      skipped: [{ path: com, image: com }],
      refusal: { code: "EFTYPE", path: com },
    });
    writeFileSync(com, image());
    expect(resolveHarnessCommandOnPath("tool", dir, "win32").command?.entrypoint).toBe(com);
  });

  it("gives the broken-install advisory (login, Codex doctor) the refusal's own wording", async () => {
    const prefix = join(root, "npm");
    const { target } = npmInstall(prefix, PLACEHOLDER);
    const advisory = await onWindows(async () =>
      brokenInstallAdvisory("tool", { HOME: join(root, "home"), PATH: prefix }),
    );
    expect(advisory).toMatch(
      new RegExp(`^${escaped(`Cannot launch ${target}: it is not a Windows executable image`)}`),
    );
  });

  it.skipIf(process.platform === "win32" || process.getuid?.() === 0)(
    "keeps an unreadable file a candidate: an unknown read is not proof",
    () => {
      const dir = join(root, "bin");
      const locked = file(join(dir, "tool.exe"), PLACEHOLDER);
      chmodSync(locked, 0o000);
      try {
        const resolution = resolveHarnessCommandOnPath("tool", dir, "win32");
        expect(resolution.command?.entrypoint).toBe(locked);
        expect(resolution.refusal ?? null).toBeNull();
      } finally {
        chmodSync(locked, 0o600);
      }
    },
  );
});

describe("the bare-name fallback libuv would search", () => {
  // libuv searches the cwd unless the parent sets this (NeedCurrentDirectoryForExePathW).
  beforeEach(() => {
    vi.stubEnv("NoDefaultCurrentDirectoryInExePath", undefined);
  });
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("refuses a cwd placeholder with an empty PATH or a PATH whose candidates were rejected", async () => {
    const work = join(root, "work");
    const placeholder = file(join(work, "tool.exe"), PLACEHOLDER);
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work)),
    ).toMatchObject({
      code: "EFTYPE",
      path: placeholder,
      message: expect.stringContaining(
        `Cannot launch ${placeholder}: it is not a Windows executable image;`,
      ),
    });
    const prefix = join(root, "npm");
    npmInstall(prefix, PLACEHOLDER);
    // libuv looks in the cwd before PATH, so the cwd file is what it would run.
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: prefix }, "win32", work)),
    ).toMatchObject({
      code: "EFTYPE",
      path: placeholder,
    });
    const options = { env: { PATH: "" }, cwd: work };
    await expect(onWindows(() => runCapture("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: placeholder,
    });
    await expect(onWindows(() => runCaptureRaw("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: placeholder,
    });
    expect(observer.attempts).toEqual([]);
  });

  it("never lets a proven-broken install fall through to an image the resolver did not select", async () => {
    const prefix = join(root, "npm");
    const { target } = npmInstall(prefix, PLACEHOLDER);
    const work = join(root, "work");
    // libuv would start this cwd image; spawning the broken install never searched the cwd.
    file(join(work, "tool.exe"), image());
    expect(resolveHarnessCommandOnPath("tool", prefix, "win32", {}, work).refusal).toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    const options = { env: { PATH: prefix }, cwd: work };
    await expect(onWindows(() => runCapture("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    await expect(onWindows(() => runCaptureRaw("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    expect(observer.attempts).toEqual([]);
    // A healthy selected alternative still runs, by its absolute path.
    const healthy = file(join(root, "healthy", "tool.exe"), image());
    const path = [prefix, dirname(healthy)].join(delimiter);
    expect(prepareHarnessCommand("tool", [], { PATH: path }, "win32", work).binary).toBe(healthy);
  });

  it("leaves a missing or healthy lookup to the OS, trying `.com` before `.exe` like libuv", () => {
    const work = join(root, "work");
    mkdirSync(work);
    // Nothing anywhere: the OS reports ENOENT, as before.
    expect(prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work).binary).toBe("tool");
    // A launcher whose declared target is missing proves nothing about an image.
    const prefix = join(root, "npm");
    rmSync(npmInstall(prefix, image()).target);
    const missing = prepareHarnessCommand("tool", [], { PATH: prefix }, "win32", work);
    expect(missing.binary).toBe("tool");
    expect(missing.resolution.skipped).toEqual([
      { path: join(prefix, "tool.cmd"), reason: "is not a supported standard npm launcher" },
    ]);
    // A real image in the cwd remains the OS's own choice.
    file(join(work, "tool.exe"), image());
    expect(prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work).binary).toBe("tool");
    const com = file(join(work, "tool.com"), PLACEHOLDER);
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work)),
    ).toMatchObject({
      code: "EFTYPE",
      path: com,
    });
  });

  it("does not search the cwd when the parent opted out, exactly as libuv", () => {
    vi.stubEnv("NoDefaultCurrentDirectoryInExePath", "1");
    const work = join(root, "work");
    file(join(work, "tool.exe"), PLACEHOLDER);
    expect(prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work).binary).toBe("tool");
    const dir = join(root, "bin");
    const placeholder = file(join(dir, "tool.exe"), PLACEHOLDER);
    expect(
      thrown(() => prepareHarnessCommand("tool", [], { PATH: dir }, "win32", work)),
    ).toMatchObject({ code: "EFTYPE", path: placeholder });
  });
});

describe("PATH as a Windows spawn reads it", () => {
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("keeps a quoted entry that contains the delimiter whole, as libuv does", async () => {
    const quoted = join(root, `npm${delimiter}prefix`);
    const { target } = npmInstall(quoted, PLACEHOLDER);
    for (const path of [`"${quoted}"`, `'${quoted}'`]) {
      expect(resolveHarnessCommandOnPath("tool", path, "win32")).toMatchObject({
        command: null,
        refusal: { code: "EFTYPE", path: target },
      });
    }
    await expect(
      onWindows(() => runCapture("tool", [], { env: { PATH: `"${quoted}"` }, cwd: root })),
    ).rejects.toMatchObject({ code: "EFTYPE", path: target });
    expect(observer.attempts).toEqual([]);
    // Healthy, it is selected ahead of a broken later entry.
    writeFileSync(target, image());
    const broken = file(join(root, "broken", "tool.exe"), PLACEHOLDER);
    const path = [`"${quoted}"`, dirname(broken)].join(delimiter);
    expect(resolveHarnessCommandOnPath("tool", path, "win32").command?.entrypoint).toBe(target);
    // A Node entry finds its interpreter through a quoted entry too.
    const scripts = join(root, "scripts");
    const { target: script } = npmInstall(scripts, NODE_SCRIPT, "node");
    const runtime = file(join(root, `node${delimiter}runtime`, "node.exe"), image());
    const runtimePath = [scripts, `"${dirname(runtime)}"`].join(delimiter);
    const command = prepareHarnessCommand("tool", [], { PATH: runtimePath }, "win32", root);
    expect(command.binary).toBe(runtime);
    expect(command.args).toEqual([script]);
  });

  it("preserves quoted PATH entries through normalization and the inherited capture path", async () => {
    const quoted = join(root, `npm${delimiter}${delimiter}prefix`);
    const { target } = npmInstall(quoted, PLACEHOLDER);
    for (const quote of ['"', "'"]) {
      const source = { HOME: root, PATH: `${quote}${quoted}${quote}` };
      const path = normalizedHarnessPath(source, "", "win32");
      expect(path).toContain(source.PATH);
      expect(resolveHarnessCommandOnPath("tool", path, "win32").refusal).toMatchObject({
        code: "EFTYPE",
        path: target,
      });
      expect(
        await onWindows(() => Promise.resolve(brokenInstallAdvisory("tool", source))),
      ).toContain(target);
    }
    vi.stubEnv("HOME", root);
    vi.stubEnv("PATH", `"${quoted}"`);
    await expect(onWindows(() => runCapture("tool", [], { cwd: root }))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    await expect(onWindows(() => runCaptureRaw("tool", [], { cwd: root }))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    expect(observer.attempts).toEqual([]);
    writeFileSync(target, image());
    const path = normalizedHarnessPath({ HOME: root, PATH: `"${quoted}"` }, "", "win32");
    expect(resolveHarnessCommandOnPath("tool", path, "win32").command?.entrypoint).toBe(target);
  });

  it("searches the daemon's own PATH when the child env omits PATH, and none when it is empty", async () => {
    const prefix = join(root, "npm");
    const { target } = npmInstall(prefix, PLACEHOLDER);
    const work = join(root, "work");
    mkdirSync(work);
    // libuv takes the parent's PATH for a child env without one.
    vi.stubEnv("PATH", prefix);
    expect(thrown(() => prepareHarnessCommand("tool", [], {}, "win32", work))).toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    const options = { env: { PATH: null }, cwd: work };
    await expect(onWindows(() => runCapture("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    await expect(onWindows(() => runCaptureRaw("tool", [], options))).rejects.toMatchObject({
      code: "EFTYPE",
      path: target,
    });
    expect(observer.attempts).toEqual([]);
    // An empty PATH is a value: no directory is searched, so the OS reports ENOENT.
    expect(prepareHarnessCommand("tool", [], { PATH: "" }, "win32", work).binary).toBe("tool");
    writeFileSync(target, image());
    expect(prepareHarnessCommand("tool", [], {}, "win32", work).binary).toBe(target);
  });
});

